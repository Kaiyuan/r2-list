export type TranslationKey = keyof typeof en;

export function isLocale(value: string | null): value is Locale {
  return locales.some((locale) => locale.id === value);
}

export function detectLocale(language: string | null | undefined): Locale {
  const normalized = language?.toLowerCase() ?? "";
  if (normalized.startsWith("zh")) {
    return /(?:tw|hk|mo|hant)/.test(normalized) ? "zh-TW" : "zh-CN";
  }
  if (normalized.startsWith("fr")) return "fr";
  if (normalized.startsWith("ja")) return "ja";
  if (normalized.startsWith("ko")) return "ko";
  return "en";
}

export function translate(locale: Locale, key: TranslationKey, values: Record<string, string | number> = {}): string {
  return messages[locale][key].replace(/\{(\w+)\}/g, (_match, name: string) => String(values[name] ?? ""));
}

export function formatItemCount(locale: Locale, count: number): string {
  const number = new Intl.NumberFormat(locales.find((item) => item.id === locale)?.htmlLang).format(count);
  const unit = count === 1 ? messages[locale].itemSingular : messages[locale].itemPlural;
  const separator = locale.startsWith("zh") || locale === "ja" || locale === "ko" ? "" : " ";
  return `${number}${separator}${unit}`;
}